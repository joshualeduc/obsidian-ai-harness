#!/bin/bash
# 99 System/AI/PLATFORMS/android-vm/vault-mounts-hook.sh
#
# Android Terminal app (Debian VM) stand-in for the `init` workflow's
# symlinks, which Android shared storage can't hold. Run as root, after the
# vault is mounted at its usual path inside the VM:
#
#   vault-mounts-hook.sh <vault-path> <user>
#
# It bind-mounts what `init` would symlink, all inside hidden folders that
# Obsidian Sync ignores, so nothing new syncs to other devices:
#   99 System/AI/SKILLS                 -> .agents/skills  (OpenCode, Antigravity)
#   99 System/AI/SKILLS                 -> .claude/skills  (Claude Code)
#   99 System/AI/AGENTS                 -> .opencode/agents
#   99 System/AI/COMMANDS               -> .opencode/commands
#   99 System/AI/SETTINGS/opencode.json -> .opencode/opencode.json
#   99 System/AI/VAULT-MAP.md           -> .claude/CLAUDE.md  (Claude Code)
#   99 System/AI/VAULT-MAP.md           -> .agents/AGENTS.md  (Antigravity)
# and writes .opencode/opencode.jsonc, which loads VAULT-MAP.md as OpenCode
# instructions in place of the root AGENTS.md symlink; OpenCode has no hidden
# location for it. That path is absolute because OpenCode looks up relative
# `instructions` only in the folder it starts in, not from vault subfolders.
#
# A vault without "99 System/AI" is left alone. Rerunning is safe: it skips
# what is already mounted and remounts a file whose source was replaced (a
# file mount keeps showing the old file otherwise). See README.md beside this
# script for installation.

set -euo pipefail

VAULT="${1:?usage: vault-mounts-hook.sh <vault-path> <user>}"
VAULT_USER="${2:?usage: vault-mounts-hook.sh <vault-path> <user>}"
AI="$VAULT/99 System/AI"

[ -d "$AI" ] || exit 0

as_user() { runuser -u "$VAULT_USER" -- "$@"; }
is_mounted() { findmnt -rn --mountpoint "$1" >/dev/null; }

# bind SOURCE TARGET: bind-mount unless TARGET already shows SOURCE.
bind() {
    local src="$1" dest="$2"
    if is_mounted "$dest"; then
        if [ "$(stat -c '%d:%i' -- "$src")" = "$(stat -c '%d:%i' -- "$dest")" ]; then
            return 0
        fi
        umount -- "$dest"
    fi
    mount --bind -- "$src" "$dest"
    echo "mounted $dest"
}

bind_dir() {
    [ -d "$1" ] || return 0
    as_user mkdir -p -- "$2"
    bind "$1" "$2"
}

# bind_file SOURCE TARGET PLACEHOLDER: a file mount needs an existing file to
# cover. The placeholder stays on shared storage, where other apps may read it.
bind_file() {
    [ -f "$1" ] || return 0
    as_user mkdir -p -- "$(dirname -- "$2")"
    if [ ! -e "$2" ]; then
        printf '%s' "$3" | as_user tee -- "$2" >/dev/null
    fi
    bind "$1" "$2"
}

write_opencode_instructions() {
    local map="$AI/VAULT-MAP.md" file="$VAULT/.opencode/opencode.jsonc" content escaped
    [ -f "$map" ] || return 0
    escaped="${map//\\/\\\\}"
    escaped="${escaped//\"/\\\"}"
    content="// Generated by 99 System/AI/PLATFORMS/android-vm/vault-mounts-hook.sh
// for the Android Terminal VM; the vault's real config is opencode.json beside it.
{
  \"instructions\": [\"$escaped\"]
}"
    if [ "$(cat -- "$file" 2>/dev/null)" != "$content" ]; then
        as_user mkdir -p -- "$VAULT/.opencode"
        printf '%s\n' "$content" | as_user tee -- "$file" >/dev/null
        echo "wrote $file"
    fi
}

bind_dir "$AI/SKILLS" "$VAULT/.agents/skills"
bind_dir "$AI/SKILLS" "$VAULT/.claude/skills"
bind_dir "$AI/AGENTS" "$VAULT/.opencode/agents"
bind_dir "$AI/COMMANDS" "$VAULT/.opencode/commands"
bind_file "$AI/SETTINGS/opencode.json" "$VAULT/.opencode/opencode.json" '{}'
bind_file "$AI/VAULT-MAP.md" "$VAULT/.claude/CLAUDE.md" ''
bind_file "$AI/VAULT-MAP.md" "$VAULT/.agents/AGENTS.md" ''
write_opencode_instructions
